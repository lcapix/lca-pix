#!/usr/bin/env node
/**
 * Regenerates db/baseline/000-schema.sql and db/baseline/001-reference.sql
 * from the July 2026 logical dump of the dev database (the last copy taken
 * before migrate-009).
 *
 *   node scripts/db/build-baseline.mjs --dump=/path/to/lca_v3-dump-20260708-181808.sql
 *   node scripts/db/build-baseline.mjs --dump=... --check   exit 1 if the committed files differ
 *
 * The dump itself is NOT in the repo: it holds user accounts, emails, password
 * hashes and projects. This script reads only two things from it:
 *
 *   000-schema.sql     every CREATE TABLE, with AUTO_INCREMENT counters removed
 *                      and the six account profile columns removed (they come
 *                      from migrate-031-account-profile.sql, see AUTH-7)
 *   001-reference.sql  the INSERT rows of the reference/library tables named in
 *                      REFERENCE_TABLES below, and nothing else
 *
 * Rows of any other table are never read into the output. As a second guard,
 * the script refuses to write a reference INSERT whose column list names a
 * user-identifying column (email, password_hash, username, owner_id, user_id,
 * executed_by, created_by).
 *
 * Output is deterministic: the same dump gives byte-identical files.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..');
const OUT_DIR = path.join(REPO_ROOT, 'db', 'baseline');

/** Library/reference tables whose rows the migrations and tests need. */
export const REFERENCE_TABLES = [
  'impact_categories',
  'permissions',
  'substances',
  'driver_impact_factors',
  'cost_rates',
];

/** account columns that no numbered migration used to create (AUTH-7). */
export const PROFILE_COLUMNS = ['full_name', 'company', 'role', 'use_case', 'country', 'onboarded_at'];

const FORBIDDEN_COLUMNS = ['email', 'password_hash', 'username', 'owner_id', 'user_id', 'executed_by', 'created_by'];

/**
 * Split the dump into per-table sections ("-- ----- table: X -----").
 * @param {string} text
 * @returns {Map<string, string[]>} table → lines of its section
 */
export function splitSections(text) {
  const sections = new Map();
  let current = null;
  for (const line of text.split('\n')) {
    const m = /^-- ----- table: ([A-Za-z0-9_]+) -----$/.exec(line);
    if (m) {
      current = m[1];
      sections.set(current, []);
      continue;
    }
    if (current) sections.get(current).push(line);
  }
  return sections;
}

/** @param {string[]} lines */
export function createStatement(lines) {
  const start = lines.findIndex((l) => l.startsWith('CREATE TABLE '));
  if (start < 0) return null;
  const end = lines.findIndex((l, i) => i > start && /^\) ENGINE=.*;$/.test(l));
  if (end < 0) throw new Error('CREATE TABLE without a closing ") ENGINE=...;" line');
  return lines.slice(start, end + 1);
}

/**
 * @param {string} table
 * @param {string[]} create
 */
export function cleanCreate(table, create) {
  let out = create.map((l) => l.replace(/ AUTO_INCREMENT=\d+/, ''));
  if (table === 'account') {
    const before = out.length;
    out = out.filter((l) => {
      const m = /^\s+`([a-z_]+)`/.exec(l);
      return !(m && PROFILE_COLUMNS.includes(m[1]));
    });
    if (before - out.length !== PROFILE_COLUMNS.length) {
      throw new Error(`Expected to remove ${PROFILE_COLUMNS.length} profile columns from account, removed ${before - out.length}`);
    }
  }
  return out;
}

/** @param {string[]} lines */
export function insertStatements(table, lines) {
  const stmts = [];
  let cur = null;
  for (const line of lines) {
    if (line.startsWith('INSERT INTO ')) cur = [line];
    else if (cur) cur.push(line);
    if (cur && line.endsWith(';')) {
      stmts.push(cur.join('\n'));
      cur = null;
    }
  }
  for (const s of stmts) {
    const cols = /^INSERT INTO `[^`]+` \(([^)]*)\)/.exec(s);
    if (!cols) throw new Error(`${table}: INSERT without a column list`);
    const names = cols[1].split(',').map((c) => c.replace(/`/g, '').trim());
    const bad = names.filter((n) => FORBIDDEN_COLUMNS.includes(n));
    if (bad.length) throw new Error(`${table}: refusing to copy rows with user columns (${bad.join(', ')})`);
  }
  return stmts;
}

export function build(dumpText, dumpName) {
  const sections = splitSections(dumpText);
  if (sections.size === 0) throw new Error('No "-- ----- table: X -----" sections found; is this the PyMySQL logical dump?');

  const schema = [
    '-- db/baseline/000-schema.sql  (GENERATED by scripts/db/build-baseline.mjs; do not edit by hand)',
    '--',
    `-- Structure only. Every CREATE TABLE from ${dumpName}, the last`,
    '-- dump of the dev database taken before migrate-009. It is the schema the',
    '-- numbered root migrations (migrate-009 onward) were written against: the',
    '-- tables of lca_v3_drawsql_schema.sql plus database/migrations/002-008 as the',
    '-- dev database actually had them (005 was never applied there; migrate-010',
    '-- re-adds its columns guarded, so either way works).',
    '--',
    '-- Changes from the dump, made by the generator:',
    '--   * AUTO_INCREMENT counters removed.',
    `--   * account.${PROFILE_COLUMNS.join(', ')} removed: no migration`,
    '--     created them (audit AUTH-7). migrate-031-account-profile.sql adds them',
    '--     guarded, so a fresh database proves that migration works and databases',
    '--     that already have the columns are left alone.',
    '-- No row data. Reference rows are in 001-reference.sql.',
    '--',
    '-- Apply order for a fresh database: 000-schema.sql, 001-reference.sql, then',
    '-- scripts/db/migrate.mjs (see scripts/db/fresh.mjs and docs/testing/DATABASE_TESTS.md).',
    '',
    'SET NAMES utf8mb4;',
    'SET FOREIGN_KEY_CHECKS=0;',
    '',
  ];
  for (const [table, lines] of sections) {
    const create = createStatement(lines);
    if (!create) continue;
    schema.push(...cleanCreate(table, create), '');
  }
  schema.push('SET FOREIGN_KEY_CHECKS=1;', '');

  const ref = [
    '-- db/baseline/001-reference.sql  (GENERATED by scripts/db/build-baseline.mjs; do not edit by hand)',
    '--',
    `-- Reference and library rows as they stood before migrate-009, from ${dumpName}.`,
    `-- Tables: ${REFERENCE_TABLES.join(', ')}.`,
    '-- No user data: accounts, projects, cases, components, flows, runs, results,',
    '-- members and logs are never copied.',
    '--',
    '-- IDs are kept: migrate-011/012/013 write Global Warming as category_id 1,',
    '-- and the factor-data tests name factor rows 27 and 34.',
    '--',
    '-- sql_mode is relaxed for this file only: 27 legacy substances carry an empty',
    "-- category ('') that is not in the ENUM. Strict mode refuses that row; the dev",
    '-- and production databases hold it, so the seed reproduces it rather than',
    '-- hiding it (tests/db/factor-data.test.ts reports the count).',
    '',
    'SET NAMES utf8mb4;',
    'SET @lcapix_seed_old_sql_mode := @@SESSION.sql_mode;',
    "SET SESSION sql_mode = 'NO_AUTO_VALUE_ON_ZERO';",
    'SET FOREIGN_KEY_CHECKS=0;',
    '',
  ];
  for (const table of REFERENCE_TABLES) {
    const lines = sections.get(table);
    if (!lines) throw new Error(`Reference table ${table} not found in the dump`);
    const stmts = insertStatements(table, lines);
    ref.push(`-- ${table}`, ...stmts, '');
  }
  ref.push('SET FOREIGN_KEY_CHECKS=1;', 'SET SESSION sql_mode = @lcapix_seed_old_sql_mode;', '');

  return { schema: schema.join('\n'), reference: ref.join('\n') };
}

function main(argv) {
  const dumpArg = argv.find((a) => a.startsWith('--dump='));
  const check = argv.includes('--check');
  if (!dumpArg) {
    console.error('Usage: node scripts/db/build-baseline.mjs --dump=/path/to/lca_v3-dump-YYYYMMDD-HHMMSS.sql [--check]');
    return 2;
  }
  const dumpPath = path.resolve(dumpArg.slice('--dump='.length));
  const { schema, reference } = build(readFileSync(dumpPath, 'utf8'), path.basename(dumpPath));
  const files = [
    [path.join(OUT_DIR, '000-schema.sql'), schema],
    [path.join(OUT_DIR, '001-reference.sql'), reference],
  ];
  if (check) {
    let same = true;
    for (const [file, text] of files) {
      let current = '';
      try {
        current = readFileSync(file, 'utf8');
      } catch {}
      if (current !== text) {
        console.error(`${path.relative(REPO_ROOT, file)} differs from what the dump generates`);
        same = false;
      }
    }
    return same ? 0 : 1;
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [file, text] of files) {
    writeFileSync(file, text);
    console.log(`wrote ${path.relative(REPO_ROOT, file)} (${Buffer.byteLength(text)} bytes)`);
  }
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  process.exit(main(process.argv.slice(2)));
}
