// scripts/sync-epa-factors.mjs
//
// Factor integration (stop hardcoding): parse the EPA GHG Emission Factors Hub
// workbook and GENERATE a migration that upserts per-MMBtu CO2e Global-Warming
// factors for the ITAC fuels — values traced to the parsed EPA rows, not typed.
//
//   node scripts/sync-epa-factors.mjs <path-to-epa-hub.xlsx> > migrate-012-epa-fuel-factors.sql
//
// Then apply the generated SQL like any migration. Re-run each EPA release.

import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const XLSX = require('xlsx');

const GWP100 = { ch4: 28, n2o: 265 }; // IPCC AR5
// Only the MMBtu-based ITAC fuels. Natural Gas is deliberately EXCLUDED — it's
// stored per-m³ (audited 1.877 kg/m³) and ITAC gas is converted MMBtu→m³ at
// ingestion, so an MMBtu factor here would be mis-applied against the m³ unit.
const EPA_FUEL_TO_SUBSTANCE = [
  { match: /^Bituminous$/i, substance: 'Coal' },
  { match: /^Liquefied Petroleum Gases \(LPG\)$/i, substance: 'LPG' },
  { match: /^Distillate Fuel Oil No\. 2$/i, substance: 'Fuel Oil' },
  { match: /^Wood and Wood Residuals$/i, substance: 'Wood' },
];
const num = (v) => {
  if (v === null || v === undefined || v === '') return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
};

const path = process.argv[2];
if (!path) {
  console.error('usage: node scripts/sync-epa-factors.mjs <epa-hub.xlsx>');
  process.exit(1);
}
const wb = XLSX.readFile(path);
const sheet = wb.Sheets[wb.SheetNames.find((n) => /emission factors hub/i.test(n)) ?? wb.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, blankrows: false });

const mapped = [];
const seen = new Set();
for (let i = 0; i < rows.length && i < 120; i++) {
  const r = rows[i];
  if (!Array.isArray(r)) continue;
  const name = typeof r[2] === 'string' ? r[2].trim() : '';
  const co2 = num(r[4]);
  if (!name || co2 === null || co2 <= 0 || seen.has(name)) continue;
  const hit = EPA_FUEL_TO_SUBSTANCE.find((m) => m.match.test(name));
  if (!hit) continue;
  seen.add(name);
  const ch4 = num(r[5]) ?? 0;
  const n2o = num(r[6]) ?? 0;
  const co2e = Math.round((co2 + (ch4 / 1000) * GWP100.ch4 + (n2o / 1000) * GWP100.n2o) * 1000) / 1000;
  mapped.push({ substance: hit.substance, co2e, provenance: `EPA GHG Emission Factors Hub, Table 1: ${name} (CO2 ${co2} + CH4 ${ch4}g + N2O ${n2o}g /MMBtu → CO2e)` });
}

if (mapped.length < 3) {
  console.error(`Only parsed ${mapped.length} fuel rows — aborting (expected >= 4). Check the sheet layout.`);
  process.exit(2);
}

const esc = (s) => s.replace(/'/g, "''");
const values = mapped
  .map((m) => `  SELECT '${esc(m.substance)}' AS name, ${m.co2e} AS co2e, '${esc(m.provenance)}' AS prov`)
  .join('\n  UNION ALL\n');

process.stdout.write(`-- migrate-012-epa-fuel-factors.sql  (GENERATED by scripts/sync-epa-factors.mjs)
-- Per-MMBtu CO2e Global Warming factors for ITAC fuels, parsed from the EPA GHG
-- Emission Factors Hub (Table 1) — CO2 + CH4 + N2O combined at IPCC AR5 GWP100.
-- Supersedes the hand-entered CO2-only values in migrate-011. Re-generate on each
-- EPA release: node scripts/sync-epa-factors.mjs <hub.xlsx> > migrate-012-epa-fuel-factors.sql
-- Parsed ${mapped.length} fuels: ${mapped.map((m) => m.substance).join(', ')}.

DELETE dif FROM driver_impact_factors dif
JOIN substances s ON s.substance_id = dif.substance_id
WHERE s.substance_name IN (${mapped.map((m) => `'${esc(m.substance)}'`).join(', ')})
  AND dif.category_id = 1;

INSERT INTO driver_impact_factors
  (substance_id, category_id, method_name, factor_value, unit,
   geographic_scope, source_reference, factor_basis)
SELECT s.substance_id, 1, m.method_name, v.co2e, 'kg CO2 eq / MMBtu', 'Global', v.prov, 'embodied'
FROM (
${values}
) v
JOIN substances s ON s.substance_name = v.name
CROSS JOIN (
  SELECT 'CML 2001' AS method_name
  UNION ALL SELECT 'ReCiPe Midpoint (H)'
  UNION ALL SELECT 'TRACI 2.1'
) m;
`);
