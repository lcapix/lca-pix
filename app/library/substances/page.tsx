'use client'

import { useEffect, useMemo, useState } from 'react'
import { useRouter } from 'next/navigation'
import { AuthGuard } from '@/components/auth-guard'
import { AppTopBar, Icon, SectionHeader } from '@/components/lcapix'
import { useAuthStore } from '@/lib/store'
import { apiRequest } from '@/lib/api-client'

/**
 * /library/substances
 *
 * User-facing page for the substance catalog. Reached from the "Browse
 * substance catalog" / "View components" CTA on the COMPONENTS KPI tile on
 * /home. These are the building blocks (materials, fuels, emissions, waste,
 * water) that user-defined components are composed of.
 */

interface SubstanceRow {
  substance_id: number
  substance_name: string
  cas_number: string | null
  category: string | null
  default_unit: string | null
  description?: string | null
  enriched_at?: string | null
}

const CATEGORY_LABELS: Record<string, string> = {
  material: 'Materials',
  energy: 'Energy carriers',
  emission: 'Emissions',
  waste: 'Waste streams',
  water: 'Water',
}

const CATEGORY_BLURBS: Record<string, string> = {
  material:
    'Raw and intermediate materials — steel, aluminum, plastics, etc. Tracked by mass.',
  energy:
    'Energy carriers like electricity, natural gas, and diesel. Tracked by energy content or volume.',
  emission:
    'Substances released to air, water, or soil — CO₂, NOx, particulates.',
  waste:
    'Solid or hazardous waste streams generated by a process.',
  water:
    'Water withdrawal, consumption, and discharge by quality class.',
}

export default function SubstancesLibraryPage() {
  const router = useRouter()
  const user = useAuthStore((s) => s.user)
  const userInitials = useMemo(
    () =>
      (user?.name ?? user?.email ?? 'U')
        .split(/\s+/)
        .map((p) => p[0])
        .join('')
        .slice(0, 2)
        .toUpperCase(),
    [user],
  )

  const [rows, setRows] = useState<SubstanceRow[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [search, setSearch] = useState('')
  const [activeCategory, setActiveCategory] = useState<string | null>(null)

  useEffect(() => {
    if (!user) return
    let cancelled = false
    setLoading(true)
    apiRequest('/api/substances')
      .then((r) => r.json())
      .then((data) => {
        if (cancelled) return
        const list: SubstanceRow[] = Array.isArray(data?.substances)
          ? data.substances
          : Array.isArray(data)
            ? data
            : []
        setRows(list)
        setLoading(false)
      })
      .catch((e) => {
        if (cancelled) return
        setError(e?.message ?? 'Failed to load substance catalog.')
        setLoading(false)
      })
    return () => {
      cancelled = true
    }
  }, [user])

  const groupCounts = useMemo(() => {
    const m = new Map<string, number>()
    rows.forEach((s) => {
      const c = s.category ?? 'uncategorized'
      m.set(c, (m.get(c) ?? 0) + 1)
    })
    return Array.from(m.entries())
      .map(([category, count]) => ({ category, count }))
      .sort((a, b) => b.count - a.count)
  }, [rows])

  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase()
    return rows.filter((s) => {
      if (activeCategory && s.category !== activeCategory) return false
      if (!q) return true
      return (
        (s.substance_name ?? '').toLowerCase().includes(q) ||
        (s.cas_number ?? '').toLowerCase().includes(q) ||
        (s.category ?? '').toLowerCase().includes(q)
      )
    })
  }, [rows, search, activeCategory])

  return (
    <AuthGuard>
      <div className="app-shell">
        <AppTopBar current="integrations" userInitials={userInitials} />

        <div
          style={{
            padding: '32px 32px 80px',
            maxWidth: 1280,
            margin: '0 auto',
          }}
        >
          {/* Back */}
          <button
            onClick={() => router.push('/home')}
            className="press-active"
            style={{
              background: 'transparent',
              border: 'none',
              color: 'var(--text-tertiary)',
              fontSize: 12,
              cursor: 'pointer',
              display: 'inline-flex',
              alignItems: 'center',
              gap: 6,
              padding: 0,
              marginBottom: 16,
            }}
          >
            <Icon name="arrow-up-right" size={11} style={{ transform: 'rotate(180deg)' }} />
            Back to home
          </button>

          {/* Header */}
          <SectionHeader
            as="h1"
            eyebrow="LIBRARY"
            title="Substance catalog"
            sub={`${rows.length.toLocaleString()} substances across ${groupCounts.length} categories.`}
            style={{ marginBottom: 28 }}
          />

          {/* Explainer */}
          <div
            style={{
              background: 'var(--surface-raised)',
              border: '1px solid var(--border-subtle)',
              borderRadius: 12,
              padding: '18px 20px',
              margin: '20px 0 28px',
              fontSize: 13.5,
              lineHeight: 1.6,
              color: 'var(--text-secondary)',
            }}
          >
            <div
              style={{
                fontSize: 11,
                letterSpacing: '0.14em',
                color: 'var(--text-tertiary)',
                marginBottom: 6,
                fontWeight: 600,
              }}
            >
              SUBSTANCES vs COMPONENTS
            </div>
            <p style={{ margin: 0 }}>
              A <strong>substance</strong> is a single tracked input or output —
              a kg of steel, a kWh of electricity, a kg of CO₂ emitted. A{' '}
              <strong>component</strong> in your project is a process step
              (machining, welding, transport) that <em>uses</em> these
              substances as drivers.
            </p>
            <p style={{ margin: '10px 0 0' }}>
              CAS numbers (where available) link substances to regulatory and
              chemistry databases. The <span className="mono">default_unit</span>{' '}
              is what the catalog assumes when a project doesn't override it.
            </p>
          </div>

          {/* Category cards */}
          {groupCounts.length > 0 && (
            <div
              style={{
                display: 'grid',
                gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))',
                gap: 12,
                marginBottom: 24,
              }}
            >
              {groupCounts.map(({ category, count }) => {
                const isActive = activeCategory === category
                return (
                  <button
                    key={category}
                    onClick={() =>
                      setActiveCategory(isActive ? null : category)
                    }
                    className="press-active"
                    style={{
                      textAlign: 'left',
                      background: isActive
                        ? 'var(--brand-subtle)'
                        : 'var(--surface-raised)',
                      border:
                        '1px solid ' +
                        (isActive
                          ? 'var(--brand-primary)'
                          : 'var(--border-subtle)'),
                      borderRadius: 10,
                      padding: '14px 16px',
                      cursor: 'pointer',
                      fontFamily: 'inherit',
                    }}
                  >
                    <div
                      style={{
                        fontSize: 11,
                        letterSpacing: '0.1em',
                        color: 'var(--text-tertiary)',
                        textTransform: 'uppercase',
                        marginBottom: 4,
                      }}
                    >
                      {CATEGORY_LABELS[category] ?? category}
                    </div>
                    <div
                      className="mono"
                      style={{
                        fontSize: 22,
                        fontWeight: 600,
                        color: 'var(--text-primary)',
                      }}
                    >
                      {count}
                    </div>
                    <div
                      style={{
                        fontSize: 12,
                        color: 'var(--text-tertiary)',
                        marginTop: 4,
                        lineHeight: 1.4,
                      }}
                    >
                      {CATEGORY_BLURBS[category] ?? 'Uncategorized substances.'}
                    </div>
                  </button>
                )
              })}
            </div>
          )}

          {/* Search */}
          <div
            style={{
              display: 'flex',
              alignItems: 'center',
              gap: 8,
              background: 'var(--surface-raised)',
              border: '1px solid var(--border-subtle)',
              borderRadius: 8,
              padding: '0 12px',
              height: 38,
              marginBottom: 16,
              maxWidth: 420,
            }}
          >
            <Icon name="search" size={14} style={{ color: 'var(--text-tertiary)' }} />
            <input
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Search by name, CAS number, or category…"
              style={{
                flex: 1,
                background: 'transparent',
                border: 'none',
                outline: 'none',
                fontSize: 13.5,
                color: 'var(--text-primary)',
                fontFamily: 'var(--font-ui)',
              }}
            />
            {activeCategory && (
              <button
                onClick={() => setActiveCategory(null)}
                style={{
                  background: 'transparent',
                  border: 'none',
                  color: 'var(--text-tertiary)',
                  fontSize: 12,
                  cursor: 'pointer',
                }}
              >
                Clear filter
              </button>
            )}
          </div>

          {/* Table */}
          {loading ? (
            <div
              style={{
                padding: 40,
                textAlign: 'center',
                color: 'var(--text-tertiary)',
              }}
            >
              Loading substance catalog…
            </div>
          ) : error ? (
            <div
              style={{
                padding: 20,
                border: '1px solid var(--border-subtle)',
                borderRadius: 10,
                color: 'var(--signal-danger, #dc2626)',
              }}
            >
              {error}
            </div>
          ) : filtered.length === 0 ? (
            <div
              style={{
                padding: 40,
                textAlign: 'center',
                color: 'var(--text-tertiary)',
                border: '1px dashed var(--border-subtle)',
                borderRadius: 10,
              }}
            >
              No substances match your search.
            </div>
          ) : (
            <div
              style={{
                border: '1px solid var(--border-subtle)',
                borderRadius: 10,
                overflow: 'hidden',
                background: 'var(--surface-card, #fff)',
              }}
            >
              <table style={{ width: '100%', borderCollapse: 'collapse', fontSize: 13 }}>
                <thead>
                  <tr style={{ background: 'var(--surface-raised)' }}>
                    <Th>Substance</Th>
                    <Th>CAS</Th>
                    <Th>Category</Th>
                    <Th>Default unit</Th>
                  </tr>
                </thead>
                <tbody>
                  {filtered.slice(0, 200).map((s) => (
                    <tr
                      key={s.substance_id}
                      style={{
                        borderTop: '1px solid var(--border-subtle)',
                      }}
                    >
                      <Td>{s.substance_name}</Td>
                      <Td mono>{s.cas_number ?? '—'}</Td>
                      <Td>{s.category ?? '—'}</Td>
                      <Td mono>{s.default_unit ?? '—'}</Td>
                    </tr>
                  ))}
                </tbody>
              </table>
              {filtered.length > 200 && (
                <div
                  style={{
                    padding: '10px 14px',
                    fontSize: 12,
                    color: 'var(--text-tertiary)',
                    borderTop: '1px solid var(--border-subtle)',
                  }}
                >
                  Showing first 200 of {filtered.length}. Narrow the search to
                  see more.
                </div>
              )}
            </div>
          )}
        </div>
      </div>
    </AuthGuard>
  )
}

function Th({ children }: { children: React.ReactNode }) {
  return (
    <th
      style={{
        textAlign: 'left',
        padding: '10px 14px',
        fontSize: 11,
        fontWeight: 600,
        letterSpacing: '0.08em',
        textTransform: 'uppercase',
        color: 'var(--text-tertiary)',
      }}
    >
      {children}
    </th>
  )
}

function Td({
  children,
  mono = false,
}: {
  children: React.ReactNode
  mono?: boolean
}) {
  return (
    <td
      className={mono ? 'mono' : ''}
      style={{
        padding: '10px 14px',
        color: 'var(--text-primary)',
      }}
    >
      {children}
    </td>
  )
}
