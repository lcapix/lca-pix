-- Assignments and frozen hand-ins. A class shares one template case.
-- Hand-in copies the student's working case into a read-only case.

CREATE TABLE assignment (
  assignment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES project (project_id) ON DELETE CASCADE,
  title varchar(200) COLLATE ci NOT NULL,
  instructions text COLLATE ci,
  due_at timestamptz,
  template_case_id integer,
  created_by integer REFERENCES account (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE submission (
  submission_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES assignment (assignment_id) ON DELETE CASCADE,
  account_id integer NOT NULL REFERENCES account (id),
  working_case_id integer REFERENCES case_table (case_id) ON DELETE SET NULL,
  frozen_case_id integer REFERENCES case_table (case_id) ON DELETE SET NULL,
  run_id integer REFERENCES assessment_runs (run_id) ON DELETE SET NULL,
  submitted_at timestamptz,
  UNIQUE (assignment_id, account_id)
);

ALTER TABLE case_table ADD COLUMN assignment_id integer;
ALTER TABLE assignment
  ADD CONSTRAINT assignment_template_case_fk
  FOREIGN KEY (template_case_id) REFERENCES case_table (case_id) ON DELETE SET NULL;
ALTER TABLE case_table
  ADD CONSTRAINT case_table_assignment_fk
  FOREIGN KEY (assignment_id) REFERENCES assignment (assignment_id) ON DELETE SET NULL;

-- The baseline's rule for every table with updated_at (000-schema.sql).
CREATE TRIGGER "assignment__set_updated_at" BEFORE UPDATE ON "assignment" FOR EACH ROW EXECUTE FUNCTION set_updated_at();
